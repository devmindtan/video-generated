const assert = require('node:assert/strict');
const {readMusicEdit} = require('./read-music-edit.cjs');
const clip = '<Audio name="Experience test" src={staticFile("test.wav")} from={4 * fps} trimBefore={12 * fps} durationInFrames={20 * fps} playbackRate={1.25} volume={0.3} />';
assert.deepEqual(readMusicEdit(clip), {src: 'test.wav', from: 120, trimBefore: 360, durationInFrames: 600, playbackRate: 1.25, volume: .3});
assert.equal(readMusicEdit(clip.replace('4 * fps', '-30')).from, -30);
assert.equal(readMusicEdit(clip.replace('20 * fps', '(8 + 3) * fps')).durationInFrames, 330);
assert.equal(readMusicEdit(clip.replace('durationInFrames={20 * fps}', '')).durationInFrames, null);
assert.throws(() => readMusicEdit(clip.replace('4 * fps', 'music.start')), /Unsupported/);
assert.throws(() => readMusicEdit('<>' + clip + clip + '</>'), /exactly one/);
assert.throws(() => readMusicEdit(clip.replace('1.25', '1 / 0')), /Invalid/);
const current = readMusicEdit(require('node:fs').readFileSync(require('node:path').resolve(__dirname, '../../../src/projects/single-task/Video.tsx'), 'utf8'));
assert.match(current.src, /reverb-full/);
assert.equal(current.volume, null);
assert.equal(readMusicEdit(clip.replace('volume={0.3}', 'volume={singleTaskMusicVolume(frame, fps)}')).volume, null);
assert.throws(() => readMusicEdit(clip.replace('volume={0.3}', 'volume={unknownVolume(frame, fps)}')), /Unsupported/);
const interworld = clip.replace('Experience test', 'INTERWORLD test').replace('volume={0.3}', 'volume={rightAdviceMusicVolume(frame, fps)}');
assert.equal(readMusicEdit(interworld, 30, 'rightAdviceMusicVolume', 'INTERWORLD').volume, null);
assert.throws(() => readMusicEdit(interworld), /exactly one/);
console.log('Music Edit: 13 offline checks passed (editable timing; caption ducking restored; configurable track prefix; unknown expressions rejected).');

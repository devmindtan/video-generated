/* Read-only browser QA against the real local workspace. Writes screenshots only to .cache/. */
const {chromium}=require('playwright-core');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');

async function run(){
  const base=process.env.MANAGER_TEST_URL||'http://127.0.0.1:4310';
  const executable=process.env.CHROME_PATH||'/usr/bin/google-chrome';
  const output=path.resolve('.cache/project-manager/qa');fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({headless:true,executablePath:executable});
  const page=await browser.newPage({viewport:{width:1440,height:1000},locale:'vi-VN'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  const report={checks:[],screenshots:[],pageErrors:errors,mutationsSubmitted:0};
  const mark=name=>{report.checks.push(name);console.log('✓ '+name);};
  const screenshot=async name=>{await page.screenshot({path:path.join(output,name+'.png'),fullPage:false});report.screenshots.push(name+'.png');};
  const noOverflow=async()=>assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Unexpected horizontal overflow');
  try{
    await page.goto(base,{waitUntil:'networkidle'});
    await page.waitForSelector('.project-card');
    await page.waitForFunction(()=>[...document.querySelectorAll('.project-card img')].slice(0,3).every(i=>i.complete&&i.naturalWidth>0));
    await noOverflow();await screenshot('desktop');mark('Desktop: catalog, visible previews and no horizontal overflow');
    const search=page.getByRole('searchbox',{name:'Tìm dự án'});
    await search.fill('mot ngay lam chua tot');await page.waitForTimeout(200);
    assert.equal(await page.locator('.project-card').count(),1);assert.match(await page.locator('.card-title').innerText(),/một ngày làm chưa tốt/i);
    mark('Accent-insensitive search finds the existing episode');
    await page.locator('[data-watch="video"]').click();await page.locator('#media-dialog[open] video').waitFor();
    await page.waitForFunction(()=>document.querySelector('#media-content video')?.readyState>=1);
    assert.ok(await page.locator('#media-content video').evaluate(v=>v.duration>0&&v.controls&&!v.autoplay));
    await page.locator('#media-content video').evaluate(v=>{v.currentTime=3;});
    await page.waitForFunction(()=>document.querySelector('#media-content video')?.readyState>=2);
    await screenshot('video-player');await page.locator('#close-media').click();
    await page.waitForFunction(()=>!document.querySelector('#media-content video'));mark('Rendered video plays locally with native controls, no autoplay, and releases source on close');
    await page.locator('[data-watch="thumbnail"]').click();await page.locator('#media-dialog[open] img').waitFor();
    await page.waitForFunction(()=>document.querySelector('#media-content img')?.naturalWidth>0);
    await screenshot('rendered-thumbnail');await page.locator('#close-media').click();mark('Rendered thumbnail opens directly; Studio action remains available');
    await page.locator('.card-title').click();await page.waitForSelector('#drawer:not([hidden])');
    await page.waitForFunction(()=>document.querySelector('#document-view h1'));
    assert.ok(await page.locator('.workspace').evaluate(n=>n.inert));
    await noOverflow();await screenshot('project-detail');mark('Detail opens script and locks background focus/scroll');
    await page.locator('[data-delete-project]').click();await page.locator('#delete-dialog[open]').waitFor();
    assert.match(await page.locator('#delete-summary').innerText(),/bản dựng\/thumbnail/);
    await screenshot('delete-confirmation');await page.locator('#cancel-delete').click();mark('Production deletion shows inventory and cancels without mutation');
    const notes=page.locator('#notes-text'),original=await notes.inputValue();
    await notes.fill(original+'\nBrowser-only unsaved draft');
    page.once('dialog',dialog=>dialog.dismiss());await page.locator('#close-drawer').click();
    assert.ok(await page.locator('#drawer').isVisible());assert.match(await notes.inputValue(),/unsaved draft/);
    await notes.fill(original);await page.locator('#close-drawer').click();mark('Unsaved notes are guarded; test leaves original notes unchanged');
    await search.fill('');await page.waitForTimeout(180);
    await page.locator('#series-filter').selectOption('tiny-dino');await page.waitForTimeout(100);
    assert.equal(await page.locator('.project-card').count(),2);mark('Series filter shows the two Tí Hon projects');
    await page.locator('[data-nav="books"]').click();await page.locator('.book-card').first().waitFor();
    await page.locator('.book-card .card-title').filter({hasText:'Hiểu về trái tim'}).click();await page.locator('[data-book-document="season-plan.md"]').waitFor();
    await page.waitForFunction(()=>document.querySelector('#document-view h1'));
    assert.equal(await page.locator('#book-upload').count(),1);
    await screenshot('book-research');await page.locator('#close-drawer').click();mark('Book library and research document are readable');
    await page.locator('#new-book-button').click();await page.locator('#create-dialog[open]').waitFor();
    await page.locator('input[name="title"]').fill('Một cuốn sách khác');assert.equal(await page.locator('input[name="id"]').inputValue(),'mot-cuon-sach-khac');
    await screenshot('book-form');await page.locator('#cancel-create').click();mark('Additional book form supports independent title, author and source record; no submit');
    await page.locator('#new-project-button').click();await page.locator('#create-dialog[open]').waitFor();
    await page.locator('#create-series').selectOption('book-insights');
    await page.locator('#create-fields input[name="title"]').fill('Tập thử trên trình duyệt');
    assert.match(await page.locator('#create-fields input[name="id"]').inputValue(),/^tap-thu/);
    assert.equal(await page.locator('#create-format').inputValue(),'long');
    assert.equal(await page.locator('input[name="duration"]').inputValue(),'');
    await screenshot('project-form');await page.locator('#cancel-create').click();mark('Planning form derives slug and leaves long duration unapproved; no submit');
    assert.equal(await page.locator('#new-series-button, #delete-series-button').count(),0);mark('No series create/delete actions');
    assert.deepEqual(await page.locator('#navigation .nav-channel').allInnerTexts().then(t=>t.map(x=>x.replace(/\s*\d+$/,''))),['Tâm lý cuộc sống','Kênh thiếu nhi','Video khách hàng']);
    assert.equal(await page.locator('#navigation').getByText('Toàn bộ kênh').count(),0);mark('Sidebar lists two content channels as links, client work apart');
    await page.setViewportSize({width:768,height:1000});await page.locator('[data-nav="all"]').click();await noOverflow();await screenshot('tablet');mark('Tablet layout has no horizontal overflow');
    await page.setViewportSize({width:390,height:844});await page.locator('#mobile-menu').click();
    assert.ok(await page.locator('#menu-backdrop').isVisible());await screenshot('mobile-menu');
    await page.locator('[data-nav="all"]').click();assert.ok(await page.locator('#menu-backdrop').isHidden());
    await noOverflow();await screenshot('mobile');
    assert.equal(await page.locator('#new-project-button').isVisible(),true);mark('Mobile menu/backdrop and create project action remain usable');
    await search.fill('mot ngay lam chua tot');await page.waitForTimeout(180);await page.locator('.card-title').click();
    await page.locator('#drawer:not([hidden])').waitFor();await page.waitForFunction(()=>document.querySelector('#document-view h1'));await noOverflow();await screenshot('mobile-detail');
    await page.keyboard.press('Escape');assert.ok(await page.locator('#drawer').isHidden());mark('Mobile detail fits and closes with Escape');
    assert.deepEqual(errors,[]);mark('No browser JavaScript or console errors');
    fs.writeFileSync(path.join(output,'report.json'),JSON.stringify(report,null,2)+'\n');
  }finally{await browser.close();}
}
run().catch(error=>{console.error(error);process.exitCode=1;});

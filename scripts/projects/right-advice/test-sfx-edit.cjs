const assert = require('node:assert/strict');
const {readSfxEdit} = require('./read-sfx-edit.cjs');
const config = {enabled: true, windVolume: .8};
const source = '<Audio name="test" from={17.966666666666665 * fps} trimBefore={3} durationInFrames={2.2 * fps} src={staticFile("right-advice/audio/sound-v2/test.wav")} volume={sfx.windVolume} />';
const read = (s = source, c = config) => readSfxEdit(s, c);
assert.ok(Math.abs(read()[0].from - 539) < 1e-9);
assert.equal(read()[0].volume, .8);
assert.equal(read()[0].trimBefore, 3);
assert.equal(read()[0].durationInFrames, 66);
assert.equal(read(source.replace('2.2 * fps', '1 * fps'))[0].durationInFrames, 30);
assert.equal(read(source.replace('17.966666666666665 * fps', '-30'))[0].from, -30);
assert.equal(read(source.replace('volume={sfx.windVolume}', 'volume={0.25}'))[0].volume, .25);
assert.equal(read(source.replace('sfx.windVolume}', 'rightAdviceSfxBedVolume(frame, fps, sfx.windVolume)}'))[0].ducked, true);
assert.equal(read(source, {...config, enabled: false}).length, 0);
assert.throws(() => read(source.replace('17.966666666666665 * fps', 'unknown.from')), /Unsupported/);
assert.throws(() => read(source.replace('sfx.windVolume', 'sfx.missing')), /Unsupported/);
assert.throws(() => read(source.replace('sfx.windVolume', 'arbitraryFunction()')), /Unsupported/);
assert.throws(() => read(source.replace('2.2 * fps', '1 / 0')), /Invalid/);
assert.throws(() => read(source.replace('trimBefore={3}', 'playbackRate={0}')), /Invalid/);
const foreground = source.replace('sfx.windVolume}', 'sfx.masterVolume * sfx.windVolume}');
const bed = source.replace('sfx.windVolume}', 'rightAdviceSfxBedVolume(frame, fps, sfx.windVolume)}');
assert.equal(read(foreground, {...config, masterVolume: .5})[0].volume, .4);
assert.equal(read(bed, {...config, masterVolume: .5})[0].volume, .4);
assert.equal(read(foreground, {...config, masterVolume: 0})[0].volume, 0);
assert.throws(() => read(source, {...config, masterVolume: -1}), /Invalid/);
console.log('SFX Edit: 18 checks passed; editable timing/gains, master volume for beds and foreground, mute and invalid values.');
